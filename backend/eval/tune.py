"""Grid-search decision-level fusion weights and band thresholds on a 70/30 split.

Reads `eval/results.csv` (generated by `python -m eval.run_eval` after human
annotations are filled in), tunes:
  1. Decision-level weights (llm, content, delivery in steps of 0.1 summing to 1.0)
  2. Performance band thresholds (Satisfactory, Good, Excellent)
on 70% of rows (stratified by quality tier), evaluates on the held-out 30%,
and prints the recommended config dicts.

Run from `backend/`:
    python -m eval.tune
"""

from __future__ import annotations

import argparse
import csv
import random
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any, Optional

BACKEND_ROOT = Path(__file__).resolve().parents[1]
if str(BACKEND_ROOT) not in sys.path:
    sys.path.insert(0, str(BACKEND_ROOT))

from app import fusion, scoring  # noqa: E402
from eval.run_eval import DEFAULT_OUT_CSV, mae, parse_float, pearson_r, spearman_rho  # noqa: E402


def classify_with_thresholds(score: float, t_sat: float, t_good: float, t_exc: float) -> str:
    if score >= t_exc:
        return "Excellent"
    if score >= t_good:
        return "Good"
    if score >= t_sat:
        return "Satisfactory"
    return "Needs Improvement"


def stratified_split(
    rows: list[dict[str, Any]],
    train_ratio: float = 0.7,
    seed: int = 42,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Deterministic 70/30 split stratified by `answer_quality` when available."""
    rng = random.Random(seed)
    buckets: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        buckets[row.get("answer_quality") or "all"].append(row)

    train_rows: list[dict[str, Any]] = []
    test_rows: list[dict[str, Any]] = []

    for key in sorted(buckets.keys()):
        group = list(buckets[key])
        rng.shuffle(group)
        if len(group) <= 1:
            train_rows.extend(group)
            continue
        split_idx = max(1, min(len(group) - 1, round(len(group) * train_ratio)))
        train_rows.extend(group[:split_idx])
        test_rows.extend(group[split_idx:])

    return train_rows, test_rows


def generate_weight_grid() -> list[dict[str, float]]:
    """Generate all (llm, content, delivery) weights in steps of 0.1 summing to 1.0."""
    grid: list[dict[str, float]] = []
    for i in range(0, 11):
        for j in range(0, 11 - i):
            k = 10 - i - j
            grid.append(
                {
                    "llm": round(i / 10.0, 1),
                    "content": round(j / 10.0, 1),
                    "delivery": round(k / 10.0, 1),
                }
            )
    return grid


def score_rows_with_weights(
    rows: list[dict[str, Any]],
    weights: dict[str, float],
) -> list[float]:
    preds: list[float] = []
    for row in rows:
        delivery = parse_float(row.get("delivery_score"))
        preds.append(
            fusion.decision_level(
                llm_score=float(row["feature_level_score"]),
                sim_reference=float(row["sim_reference"]),
                concept_coverage=float(row["concept_coverage"]),
                delivery_score_or_None=delivery,
                w=weights,
            )
        )
    return preds


def eval_regression(preds: list[float], targets: list[float]) -> dict[str, Optional[float]]:
    return {
        "mae": mae(preds, targets),
        "pearson": pearson_r(preds, targets),
        "spearman": spearman_rho(preds, targets),
    }


def eval_band_acc(
    preds: list[float],
    human_targets: list[float],
    thresholds: tuple[float, float, float],
) -> float:
    t_sat, t_good, t_exc = thresholds
    # Human reference bands use the canonical rubric thresholds (4, 6, 8)
    matches = sum(
        1
        for p, h in zip(preds, human_targets)
        if classify_with_thresholds(p, t_sat, t_good, t_exc) == scoring.band(h)
    )
    return matches / len(preds) if preds else 0.0


def tune(results_csv: Path, seed: int = 42) -> None:
    if not results_csv.is_file():
        raise FileNotFoundError(
            f"{results_csv} not found. Run `python -m eval.run_eval` first."
        )

    with results_csv.open("r", encoding="utf-8", newline="") as fh:
        raw_rows = list(csv.DictReader(fh))

    usable = [r for r in raw_rows if parse_float(r.get("human_mean")) is not None]
    if len(usable) < 6:
        raise ValueError(
            f"Need at least 6 rows with numeric `human_mean` to run 70/30 tuning (found {len(usable)}). "
            "Fill in human scores in eval/annotated_answers.csv and re-run eval/run_eval.py."
        )

    has_delivery = any(parse_float(r.get("delivery_score")) is not None for r in usable)
    train_rows, test_rows = stratified_split(usable, train_ratio=0.7, seed=seed)
    train_targets = [float(r["human_mean"]) for r in train_rows]
    test_targets = [float(r["human_mean"]) for r in test_rows]

    # 1. Grid-search decision-level weights on 70% train split
    best_weights = dict(fusion.DEFAULT_DECISION_WEIGHTS)
    best_train_mae = float("inf")
    best_train_r = -2.0

    for w in generate_weight_grid():
        if not has_delivery and (w["llm"] + w["content"] <= 0.0):
            continue
        preds = score_rows_with_weights(train_rows, w)
        metrics = eval_regression(preds, train_targets)
        cur_mae = metrics["mae"] if metrics["mae"] is not None else float("inf")
        cur_r = metrics["pearson"] if metrics["pearson"] is not None else -1.0

        # Prefer lower MAE, then higher Pearson r, then closer to default delivery weight (0.1)
        if (cur_mae < best_train_mae - 1e-9) or (
            abs(cur_mae - best_train_mae) <= 1e-9 and cur_r > best_train_r + 1e-9
        ):
            best_train_mae = cur_mae
            best_train_r = cur_r
            best_weights = w

    default_test_preds = score_rows_with_weights(test_rows, fusion.DEFAULT_DECISION_WEIGHTS)
    tuned_train_preds = score_rows_with_weights(train_rows, best_weights)
    tuned_test_preds = score_rows_with_weights(test_rows, best_weights)

    default_test_reg = eval_regression(default_test_preds, test_targets)
    tuned_train_reg = eval_regression(tuned_train_preds, train_targets)
    tuned_test_reg = eval_regression(tuned_test_preds, test_targets)

    # 2. Grid-search band thresholds (in steps of 0.5) on 70% train split
    default_thresholds = (4.0, 6.0, 8.0)
    best_thresholds = default_thresholds
    best_train_band_acc = -1.0
    best_dist_to_default = float("inf")

    sat_candidates = [round(3.0 + 0.5 * i, 1) for i in range(5)]   # 3.0 .. 5.0
    good_candidates = [round(5.0 + 0.5 * i, 1) for i in range(6)]  # 5.0 .. 7.5
    exc_candidates = [round(7.0 + 0.5 * i, 1) for i in range(5)]   # 7.0 .. 9.0

    for t_sat in sat_candidates:
        for t_good in good_candidates:
            if t_good <= t_sat:
                continue
            for t_exc in exc_candidates:
                if t_exc <= t_good:
                    continue
                acc = eval_band_acc(tuned_train_preds, train_targets, (t_sat, t_good, t_exc))
                dist = (
                    abs(t_sat - default_thresholds[0])
                    + abs(t_good - default_thresholds[1])
                    + abs(t_exc - default_thresholds[2])
                )
                if (acc > best_train_band_acc + 1e-9) or (
                    abs(acc - best_train_band_acc) <= 1e-9 and dist < best_dist_to_default
                ):
                    best_train_band_acc = acc
                    best_dist_to_default = dist
                    best_thresholds = (t_sat, t_good, t_exc)

    default_test_band_acc = eval_band_acc(default_test_preds, test_targets, default_thresholds)
    tuned_test_band_acc = eval_band_acc(tuned_test_preds, test_targets, best_thresholds)

    print(f"Tuning split (seed={seed}): train={len(train_rows)} rows (70%), held-out={len(test_rows)} rows (30%)")
    if not has_delivery:
        print(
            "Note: results.csv has text-only rows (no delivery_score); w['delivery'] is renormalized "
            "out during text-only evaluation and will be active when voice samples are included.\n"
        )

    print("=== Decision-Level Weight Search ===")
    print(f"Default weights : {fusion.DEFAULT_DECISION_WEIGHTS}")
    print(
        f"  Held-out 30%  -> MAE={default_test_reg['mae']:.3f}, "
        f"Pearson={default_test_reg['pearson'] or 0.0:.3f}, "
        f"Spearman={default_test_reg['spearman'] or 0.0:.3f}, "
        f"Band Acc={default_test_band_acc * 100:.1f}%"
    )
    print(f"Tuned weights   : {best_weights}")
    print(
        f"  Train 70%     -> MAE={tuned_train_reg['mae']:.3f}, "
        f"Pearson={tuned_train_reg['pearson'] or 0.0:.3f}, "
        f"Spearman={tuned_train_reg['spearman'] or 0.0:.3f}, "
        f"Band Acc={best_train_band_acc * 100:.1f}%"
    )
    print(
        f"  Held-out 30%  -> MAE={tuned_test_reg['mae']:.3f}, "
        f"Pearson={tuned_test_reg['pearson'] or 0.0:.3f}, "
        f"Spearman={tuned_test_reg['spearman'] or 0.0:.3f}, "
        f"Band Acc={tuned_test_band_acc * 100:.1f}%"
    )

    print("\n=== Recommended Config Values ===")
    print("# Put in backend/app/fusion.py -> DEFAULT_DECISION_WEIGHTS")
    print(f"DEFAULT_DECISION_WEIGHTS = {best_weights}")
    print("\n# Put in backend/app/scoring.py -> BAND_THRESHOLDS")
    print(
        "BAND_THRESHOLDS = {\n"
        f'    "Excellent": {best_thresholds[2]},\n'
        f'    "Good": {best_thresholds[1]},\n'
        f'    "Satisfactory": {best_thresholds[0]},\n'
        '    "Needs Improvement": 0.0,\n'
        "}"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Grid-search decision weights and band thresholds.")
    parser.add_argument("--input", type=Path, default=DEFAULT_OUT_CSV)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()
    tune(args.input, seed=args.seed)


if __name__ == "__main__":
    main()
